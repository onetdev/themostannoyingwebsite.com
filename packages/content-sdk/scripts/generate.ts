async function main() {
  const options = parseArgs();
  console.log('🚀 Starting content-sdk Swagger Generator...');

  const spec = await fetchOrReadSpec(options);
  fs.mkdirSync(options.outputDir, { recursive: true });

  // 1. Generate TypeScript definitions from OpenAPI spec using openapi-typescript
  console.log('📝 Generating OpenAPI TypeScript types...');
  const ast = await openapiTS(spec);
  const openapiTypesCode = astToString(ast);
  fs.writeFileSync(
    path.join(options.outputDir, 'openapi.ts'),
    `/**\n * Auto-generated by openapi-typescript from OpenAPI spec.\n * Do not edit manually.\n */\n\n${openapiTypesCode}\n`,
    'utf-8',
  );

  // 2. Generate Zod schemas
  console.log('⚡ Generating Zod schemas...');
  const schemasCode = generateSchemasCode();
  fs.writeFileSync(
    path.join(options.outputDir, 'schemas.ts'),
    schemasCode,
    'utf-8',
  );

  // 3. Generate Inferred Types
  console.log('🏷️  Generating inferred TypeScript types...');
  const typesCode = generateTypesCode();
  fs.writeFileSync(
    path.join(options.outputDir, 'types.ts'),
    typesCode,
    'utf-8',
  );

  // 4. Generate Endpoints Metadata
  console.log('🗺️  Generating endpoints descriptors...');
  const endpointsCode = generateEndpointsCode();
  fs.writeFileSync(
    path.join(options.outputDir, 'endpoints.ts'),
    endpointsCode,
    'utf-8',
  );

  // 5. Generate Generated Index
  fs.writeFileSync(
    path.join(options.outputDir, 'index.ts'),
    generateGeneratedIndexCode(),
    'utf-8',
  );

  // 6. Format generated files using Biome
  try {
    console.log('✨ Formatting generated files with Biome...');
    execSync('pnpm biome check --write --no-errors-on-unmatched .', {
      cwd: packageRoot,
      stdio: 'pipe',
    });
  } catch (_e) {
    // Ignore formatting warnings if biome check exits with non-zero due to hints
  }

  console.log('✅ Swagger generation completed successfully!');
}

main().catch((err) => {
  console.error('❌ Swagger generation failed:', err);
  process.exit(1);
});

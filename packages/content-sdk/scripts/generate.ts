const __dirname = path.dirname(__filename);
const packageRoot = path.resolve(__dirname, '..');

const DEFAULT_URL = 'https://content.themostannoyingwebsite.com/docs/json';
const DEFAULT_SPEC_PATH = path.join(packageRoot, 'spec', 'openapi.json');
const DEFAULT_OUTPUT_DIR = path.join(packageRoot, 'src', 'generated');

interface CliOptions {
  url: string;
  specPath: string;
  outputDir: string;
  noFetch: boolean;
}

function parseArgs(): CliOptions {
  const args = process.argv.slice(2);
  const options: CliOptions = {
    url: process.env.CONTENT_API_SPEC_URL || DEFAULT_URL,
    specPath: DEFAULT_SPEC_PATH,
    outputDir: DEFAULT_OUTPUT_DIR,
    noFetch: false,
  };

  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--url' && args[i + 1]) {
      options.url = args[++i];
    } else if (arg === '--spec' && args[i + 1]) {
      options.specPath = path.resolve(process.cwd(), args[++i]);
    } else if (arg === '--output' && args[i + 1]) {
      options.outputDir = path.resolve(process.cwd(), args[++i]);
    } else if (arg === '--no-fetch') {
      options.noFetch = true;
    }
  }

  return options;
}

async function fetchOrReadSpec(options: CliOptions): Promise<OpenAPI3> {
  let specJson: string | null = null;

  if (!options.noFetch) {
    try {
      console.log(`🌐 Fetching OpenAPI spec from ${options.url}...`);
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 10000);
      const res = await fetch(options.url, {
        headers: { Accept: 'application/json' },
        signal: controller.signal,
      });
      clearTimeout(timeoutId);

      if (!res.ok) {
        throw new Error(`HTTP error ${res.status}: ${res.statusText}`);
      }

      specJson = await res.text();
      const parsed = JSON.parse(specJson);
      fs.mkdirSync(path.dirname(options.specPath), { recursive: true });
      fs.writeFileSync(
        options.specPath,
        JSON.stringify(parsed, null, 2),
        'utf-8',
      );
      console.log(`💾 Saved cached OpenAPI spec to ${options.specPath}`);
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err);
      console.warn(`⚠️  Failed to fetch from ${options.url}: ${msg}`);
    }
  }

  if (!specJson) {
    if (fs.existsSync(options.specPath)) {
      console.log(`📂 Using existing cached spec at ${options.specPath}`);
      specJson = fs.readFileSync(options.specPath, 'utf-8');
    } else {
      throw new Error(
        `Unable to fetch spec and no cached file found at ${options.specPath}`,
      );
    }
  }

  return JSON.parse(specJson) as OpenAPI3;
}

